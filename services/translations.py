def t(key: str, locale: str = "en") -> str:
    """Get translation for key in given locale. Fallback to English."""
    lang = (locale or "en").lower()[:2]
    if lang != "tr":
        lang = "en"
    return TRANSLATIONS.get(lang, TRANSLATIONS["en"]).get(key, key)
